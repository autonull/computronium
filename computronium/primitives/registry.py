# Build the registry
def _make_spec(primitive_id: str) -> PrimitiveSpec:
    """Create a PrimitiveSpec from the collected data."""
    axis_map = {
        "credit_assignment": "credit",
        "state_dynamics": "dynamics",
        "geometry": "geometry",
        "plasticity": "plasticity",
        "substrate": "substrate",
        "parameter_update": "update",
    }
    spec_axis = primitive_id.split(".")[1]
    runtime_axis = axis_map.get(spec_axis, spec_axis)

    name = primitive_id.split(".")[-1].replace("_", " ").title()
    # Special cases for names
    name = name.replace("Pcalm", "PC-ALM").replace("Nca", "NCA").replace("Ntm", "NTM")

    kernel_entrypoint = _KERNEL_RUNGS.get(primitive_id)
    kernel_status = "implemented" if kernel_entrypoint else "absent"
    return PrimitiveSpec(
        id=primitive_id,
        axis=runtime_axis,
        name=name,
        equations="",  # TODO: extract from original specs
        invariants=_INVARIANTS.get(
            primitive_id, ("deterministic under fixed seed", "state remains finite")
        ),
        task_families=_TASK_FAMILIES.get(
            primitive_id, ("vision", "sequence", "tabular")
        ),
        ontology_class=_ONTOLOGY_CLASSES.get(primitive_id, "object"),
        config_factory=_CONFIG_FACTORIES.get(primitive_id, ""),
        reference_entrypoint=_REFERENCE_ENTRYPOINTS.get(primitive_id, ""),
        kernel_status=kernel_status,
        kernel_entrypoint=kernel_entrypoint,
        kernel_technology="torch" if kernel_entrypoint else None,
        kernel_status_reason=_KERNEL_STATUS_REASONS.get(primitive_id, ""),
        supported_backends=(
            ("reference", "kernel") if kernel_entrypoint else ("reference",)
        ),
        available=True,
        capability_card=_CAPABILITY_CARDS.get(primitive_id, ""),
        summary=_SUMMARIES.get(primitive_id, ""),
        invariants_notes="",
        tags=(),
        # Static compatibility (TODO99 #2)
        compatible_geometries=_COMPATIBLE_GEOMETRIES.get(primitive_id, ()),
        compatible_dynamics=_COMPATIBLE_DYNAMICS.get(primitive_id, ()),
        requires_readout_error=_REQUIRES_READOUT_ERROR.get(primitive_id, False),
    )


