def get_primitive_spec(primitive_id: str) -> PrimitiveSpec | None:
    """Get a PrimitiveSpec by ID."""
    return REGISTRY.get(primitive_id)


def list_primitives(axis: str | None = None) -> list[PrimitiveSpec]:
    """List all primitives, optionally filtered by axis."""
    if axis is None:
        return list(REGISTRY.values())
    return [spec for spec in REGISTRY.values() if spec.axis == axis]


def count_primitives() -> dict[str, int]:
    """Count primitives by axis."""
    counts = {}
    for spec in REGISTRY.values():
        counts[spec.axis] = counts.get(spec.axis, 0) + 1
    return counts


