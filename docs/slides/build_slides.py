"""Assemble ``docs/slides.html`` from the curated snippets in ``docs/slides/``.

One snippet is one slide: ``docs/slides/<name>.md`` becomes ``<section
id="<name>">``, so the filename is the deep-link anchor. Snippets are named for
what they say and carry no ordinal — the deck order lives in :data:`_SLIDES`,
the one place it is decided, exactly as ``docs/readme/build_readme.py`` treats
the README.

A snippet is Markdown plus three build-time markers:

* ``<!-- gen:name -->`` — a fact read from the code. The README generators are
  imported wholesale, and :data:`_SLIDE_GENERATORS` adds the matrix readings
  that only the deck needs. A stale number therefore fails the build instead of
  aging in a slide.
* ``<!-- include: path -->`` — a file, normally an SVG diagram under
  ``docs/slides/diagrams/``, inlined at build time.
* ``<!-- notes -->`` … ``<!-- /notes -->`` — speaker notes, rendered into a
  popover. Never in the slide body, never in docs mode, never in print.

The output is one file with no external requests: the template carries the CSS
and JS, diagrams are inline SVG, and images use paths relative to ``docs/``. So
``file://docs/slides.html`` is a complete deck, and an exported ``docs/``
directory is a complete documentation system.

Usage::

    uv run python docs/slides/build_slides.py [--check]
"""

from __future__ import annotations

import argparse
import importlib.util
import re
import sys
from functools import lru_cache
from pathlib import Path
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from collections.abc import Callable
    from types import ModuleType

    from markdown_it import MarkdownIt

REPO = Path(__file__).resolve().parents[2]
SNIPPET_DIR = Path(__file__).resolve().parent
TEMPLATE = SNIPPET_DIR / "_template.html"
OUTPUT = REPO / "docs" / "slides.html"
MATRIX = REPO / "docs" / "generated" / "IMPLEMENTATION_MATRIX.md"

BANNER = (
    "<!-- Generated by docs/slides/build_slides.py from docs/slides/*.md. "
    "Edit the snippets, not this file. -->"
)

_GEN_RE = re.compile(r"<!--\s*gen:([a-z_]+)\s*-->")
_INCLUDE_RE = re.compile(r"<!--\s*include:\s*([A-Za-z0-9_./-]+)\s*-->")
_NOTES_RE = re.compile(r"<!--\s*notes\s*-->(.*?)<!--\s*/notes\s*-->", re.S)
_TITLE_RE = re.compile(r"^#\s+(.+)$", re.M)
_SLUG_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")

# The deck order, declared here and nowhere else. Nine sections for eight
# beats: 03 is split into the ontology and the matrix, as the outline has it.
_SLIDES: tuple[str, ...] = (
    "epistemic-laboratory.md",
    "crisis-of-comparison.md",
    "six-axis-ontology.md",
    "implementation-matrix.md",
    "pipeline.md",
    "dashboard.md",
    "epistemic-ledger.md",
    "research-horizon.md",
    "invitation.md",
)


@lru_cache(maxsize=1)
def _readme_builder() -> ModuleType:
    """Import ``docs/readme/build_readme.py`` — the shared generator registry."""
    path = REPO / "docs" / "readme" / "build_readme.py"
    spec = importlib.util.spec_from_file_location("_slides_readme_builder", path)
    if spec is None or spec.loader is None:  # pragma: no cover - import plumbing
        msg = f"cannot import {path}"
        raise ImportError(msg)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


@lru_cache(maxsize=1)
def _matrix_rows() -> list[dict[str, str]]:
    """The implementation matrix as records, keyed by lowercased column name."""
    lines = [
        line
        for line in MATRIX.read_text(encoding="utf-8").splitlines()
        if line.startswith("|")
    ]
    header = [cell.strip().lower() for cell in lines[0].strip("|").split("|")]
    rows: list[dict[str, str]] = []
    for line in lines[2:]:
        cells = [cell.strip() for cell in line.strip("|").split("|")]
        if len(cells) != len(header):
            msg = f"{MATRIX.name}: {len(cells)} cells against {len(header)} columns"
            raise ValueError(msg)
        rows.append(dict(zip(header, cells, strict=True)))
    return rows


def _matrix_count(**match: str) -> str:
    """Number of matrix rows whose fields equal the given values."""
    return str(
        sum(
            all(row.get(key) == value for key, value in match.items())
            for row in _matrix_rows()
        )
    )


def _matrix_total() -> str:
    return str(len(_matrix_rows()))


def _matrix_primitive_count() -> str:
    return _matrix_count(kind="primitive")


def _matrix_algorithm_count() -> str:
    return _matrix_count(kind="algorithm")


def _kernel_verified_count() -> str:
    return _matrix_count(status="kernel_verified")


def _kernel_unverified_count() -> str:
    return _matrix_count(status="kernel_unverified")


def _reference_only_count() -> str:
    return _matrix_count(status="reference_only")


def _kernel_verified_table() -> str:
    """The top rung of the ladder: everything with a parity-checked kernel."""
    rows = [row for row in _matrix_rows() if row["status"] == "kernel_verified"]
    lines = ["| Implementation | Axis | Kernel |", "|---|---|---|"]
    lines.extend(
        f"| `{row['id'].removeprefix('primitive.')}` "
        f"| {row['axis'].replace('_', ' ')} "
        f"| `{row['kernel tech']}` |"
        for row in rows
    )
    return "\n".join(lines)


_SLIDE_GENERATORS: dict[str, Callable[[], str]] = {
    "matrix_total": _matrix_total,
    "matrix_primitive_count": _matrix_primitive_count,
    "matrix_algorithm_count": _matrix_algorithm_count,
    "kernel_verified_count": _kernel_verified_count,
    "kernel_unverified_count": _kernel_unverified_count,
    "reference_only_count": _reference_only_count,
    "kernel_verified_table": _kernel_verified_table,
}


@lru_cache(maxsize=1)
def _generators() -> dict[str, Callable[[], str]]:
    return {**_readme_builder()._GENERATORS, **_SLIDE_GENERATORS}


def _expand(text: str, source: str) -> str:
    """Resolve ``gen:`` and ``include:`` markers in one snippet."""

    def include(match: re.Match[str]) -> str:
        path = (SNIPPET_DIR / match.group(1)).resolve()
        if not path.is_relative_to(SNIPPET_DIR) or not path.is_file():
            msg = f"{source}: include does not resolve inside docs/slides: {match.group(1)}"
            raise FileNotFoundError(msg)
        text = path.read_text(encoding="utf-8").strip()
        # A blank line ends a CommonMark HTML block, so an SVG with blank lines
        # between groups would be half-parsed as prose.
        return re.sub(r"\n\s*\n", "\n", text)

    def gen(match: re.Match[str]) -> str:
        name = match.group(1)
        if name not in _generators():
            msg = f"{source}: unknown generated block {name!r}"
            raise KeyError(msg)
        return _generators()[name]()

    return _INCLUDE_RE.sub(include, _GEN_RE.sub(gen, text))


@lru_cache(maxsize=1)
def _renderer() -> MarkdownIt:
    from markdown_it import MarkdownIt

    md = MarkdownIt("commonmark", {"html": True, "typographer": False})
    md.enable(["table", "strikethrough"])
    return md


def _plain_title(text: str) -> str:
    """The snippet's ``# heading`` as text, for the section label."""
    match = _TITLE_RE.search(text)
    if match is None:
        msg = "slide snippet has no level-1 heading"
        raise ValueError(msg)
    return re.sub(r"\s+", " ", re.sub(r"[`*_]", "", match.group(1))).strip()


def _section(name: str, ordinal: int, text: str) -> str:
    """One snippet as one ``<section>``, notes lifted into a popover."""
    notes = [note.strip() for note in _NOTES_RE.findall(text)]
    body = _NOTES_RE.sub("", text)
    render = _renderer().render
    title = _plain_title(body)

    parts = [
        f'<section id="{name}" aria-label="{title}">',
        '<div class="stage">',
        f'<p class="kicker" aria-hidden="true">{ordinal:02d}</p>',
        render(body),
    ]
    if notes:
        note_id = f"notes-{name}"
        parts.append(
            f'<button class="notes-btn" type="button" popovertarget="{note_id}">'
            "Speaker notes</button>"
        )
    parts.append("</div>")
    if notes:
        parts.append(
            f'<div id="{note_id}" popover="auto">{render(chr(10).join(notes))}</div>'
        )
    parts.append("</section>")
    return "\n".join(parts)


def _section_files() -> list[Path]:
    files = [SNIPPET_DIR / name for name in _SLIDES]
    missing = [path.name for path in files if not path.is_file()]
    if missing:
        msg = f"manifest names snippets that do not exist: {missing}"
        raise FileNotFoundError(msg)
    return files


def _check_names(files: list[Path]) -> None:
    bad = [path.name for path in files if not _SLUG_RE.match(path.stem)]
    if bad:
        msg = f"slide snippets must be lowercase-hyphenated for stable anchors: {bad}"
        raise ValueError(msg)


def build_slides() -> str:
    """Render the whole deck, one section per snippet, in manifest order."""
    files = _section_files()
    _check_names(files)
    sections = []
    for ordinal, path in enumerate(files, start=1):
        text = _expand(path.read_text(encoding="utf-8"), source=path.name)
        sections.append(_section(path.stem, ordinal, text))

    first = files[0].read_text(encoding="utf-8")
    title = _plain_title(_NOTES_RE.sub("", _expand(first, source=files[0].name)))
    document = (
        TEMPLATE
        .read_text(encoding="utf-8")
        .replace("{{title}}", title)
        .replace("{{first_id}}", files[0].stem)
        .replace("{{slides}}", "\n\n".join(sections))
    )
    if "{{" in document:
        msg = "template placeholder left unsubstituted"
        raise ValueError(msg)
    return f"{BANNER}\n{document}"


def main(argv: list[str] | None = None) -> int:
    """Write ``docs/slides.html``, or report drift with ``--check``."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if docs/slides.html differs from the snippets (no write)",
    )
    args = parser.parse_args(argv)

    rendered = build_slides()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != rendered:
            print(
                "docs/slides.html is stale; run "
                "`uv run python docs/slides/build_slides.py`",
                file=sys.stderr,
            )
            return 1
        return 0

    OUTPUT.write_text(rendered, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
