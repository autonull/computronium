def _site_index(
    slides: tuple[Slide, ...],
    sections_about: tuple[DocSection, ...],
    sections_howto: tuple[DocSection, ...],
    map_bundle: MapBundle,
) -> str:
    items: list[dict[str, str]] = []
    for slide in slides:
        items.append({
            "set": "about",
            "id": slide.key,
            "title": slide.title,
            "kind": "slide",
        })
    for section in sections_about:
        items.append({
            "set": "docs-about",
            "id": section.key,
            "title": section.title,
            "kind": "section",
        })
        for level, heading, unique in section.headings:
            if level > 3:
                continue
            items.append({
                "set": "docs-about",
                "id": f"{section.key}/{unique}",
                "title": heading,
                "kind": "heading",
                "context": section.title,
            })
    for section in sections_howto:
        items.append({
            "set": "docs-howto",
            "id": section.key,
            "title": section.title,
            "kind": "section",
        })
        for level, heading, unique in section.headings:
            if level > 3:
                continue
            items.append({
                "set": "docs-howto",
                "id": f"{section.key}/{unique}",
                "title": heading,
                "kind": "heading",
                "context": section.title,
            })
    for panel in map_bundle.manifest["panels"]:
        items.append({
            "set": "cheatsheet",
            "id": panel["key"],
            "title": _short_title(panel["title"]),
            "kind": "panel",
        })
    return json.dumps(items, ensure_ascii=False).replace("<", "\\u003c")


def build_site() -> str:
    """Render the single-file site."""
    slides = _slides()
    sections_about = _doc_sections_about()
    sections_howto = _doc_sections_howto()
    map_bundle = _cheatsheet()
    replacements = {
        "title": "Computronium — Documentation",
        "first_id": slides[0].key,
        "first_doc_about": sections_about[0].key,
        "first_doc_howto": sections_howto[0].key,
        "about_slides": "\n\n".join(slide.html for slide in slides),
        "doc_toc_about": _doc_toc(sections_about),
        "doc_toc_howto": _doc_toc_howto(sections_howto),
        "doc_sections_about": _doc_body(sections_about, "about"),
        "doc_sections_howto": _doc_body(sections_howto, "howto"),
        "cheatsheet_index": map_bundle.index_html,
        "cheatsheet_svg": map_bundle.svg,
        "canvas_w": f"{map_bundle.canvas_w:g}",
        "canvas_h": f"{map_bundle.canvas_h:g}",
        "site_index": _site_index(slides, sections_about, sections_howto, map_bundle),
        "map_manifest": json.dumps(map_bundle.manifest, ensure_ascii=False).replace(
            "<", "\\u003c"
        ),
    }
    document = TEMPLATE.read_text(encoding="utf-8")
    for key, value in replacements.items():
        document = document.replace("{{" + key + "}}", value)
    if "{{" in document:
        msg = "template placeholder left unsubstituted"
        raise ValueError(msg)
    return f"{BANNER}\n{document}"


def build_index_md() -> str:
    """Render the plain-Markdown twin of the site."""
    parts = [
        BANNER,
        "# Computronium Documentation",
        "",
        "> Generated twin of [`index.html`](index.html). The browser site also "
        "carries the architecture cheatsheet; this file is the readable text.",
        "",
        "## About",
        "",
    ]
    parts.extend(_slide_markdown(path) for path in _slide_files())
    parts.extend(["## Documentation — About", ""])
    parts.extend(markdown for _, markdown in _raw_doc_sections(_DOC_ABOUT_KEYS))
    parts.extend(["## Documentation — HowTo", ""])
    parts.extend(markdown for _, markdown in _raw_doc_sections(_DOC_HOWTO_KEYS))
    map_bundle = _cheatsheet()
    parts.extend([
        "## Cheatsheet",
        "",
        "![Computronium architecture cheatsheet](cheatsheet/cheatsheet.svg)",
        "",
        "| Panel | Documentation |",
        "|---|---|",
    ])
    for panel in map_bundle.manifest["panels"]:
        parts.append(
            f"| {_short_title(panel['title'])} "
            f"| [`{panel['doc']}`](index.html#/docs-about/{panel['doc']}) |"
        )
    return "\n\n".join(part.strip() for part in parts if part.strip()) + "\n"


def main(argv: list[str] | None = None) -> int:
    """Write ``docs/index.html`` and ``docs/index.md``, or check for drift."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if index.html or index.md differs from the sources (no write)",
    )
    args = parser.parse_args(argv)

    rendered_html = build_site()
    rendered_md = build_index_md()
    if args.check:
        stale = False
        for path, rendered in ((OUTPUT_HTML, rendered_html), (OUTPUT_MD, rendered_md)):
            current = path.read_text(encoding="utf-8") if path.exists() else ""
            if current != rendered:
                print(
                    f"{path.relative_to(REPO)} is stale; run "
                    "`uv run python docs/build_site.py`",
                    file=sys.stderr,
                )
                stale = True
        return 1 if stale else 0

    OUTPUT_HTML.write_text(rendered_html, encoding="utf-8")
    OUTPUT_MD.write_text(rendered_md, encoding="utf-8")
    print(f"wrote {OUTPUT_HTML.relative_to(REPO)} ({len(rendered_html) // 1024} KiB)")
    print(f"wrote {OUTPUT_MD.relative_to(REPO)} ({len(rendered_md) // 1024} KiB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
