"""Assemble the self-contained Computronium documentation site.

The site is one file, ``docs/index.html``, with no external requests and no
runtime Markdown fetch. It carries three document sets:

* **About** — the curated slide snippets in ``docs/slides/``, in the order
  declared by :data:`_SLIDES`.
* **Documentation** — the README sections in ``docs/readme/``, in the order
  declared by ``build_readme._SECTIONS``, with the same generated facts
  substituted from the live code.
* **Cheatsheet** — the architecture SVG, with the panel manifest emitted by
  ``docs/cheatsheet/cheatsheet_create.py`` used as its zoom targets and its
  menu into the Documentation set.

A plain-Markdown twin is written to ``docs/index.md`` so the same content is
readable without a browser, a script, or a server.

Usage::

    uv run python docs/build_site.py [--check]
"""

