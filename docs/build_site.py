@dataclass(frozen=True, slots=True)
class MapBundle:
    svg: str
    manifest: dict[str, object]
    index_html: str
    canvas_w: float
    canvas_h: float


def _short_title(title: str) -> str:
    return re.split(r"\s+[—-]\s+", title, maxsplit=1)[0].strip()


@lru_cache(maxsize=1)
def _cheatsheet() -> MapBundle:
    if not CHEATSHEET_SVG.is_file() or not CHEATSHEET_MANIFEST.is_file():
        msg = (
            "cheatsheet artifacts are missing; run "
            "`uv run python docs/cheatsheet/cheatsheet_create.py`"
        )
        raise FileNotFoundError(msg)
    manifest = json.loads(CHEATSHEET_MANIFEST.read_text(encoding="utf-8"))
    doc_keys = {
        section.key for section in _doc_sections_about()
    } | {section.key for section in _doc_sections_howto()}
    panels = manifest["panels"]
    for panel in panels:
        if panel["doc"] not in doc_keys:
            msg = f"cheatsheet panel {panel['key']!r} opens unknown docs section {panel['doc']!r}"
            raise ValueError(msg)

    items: list[str] = []
    for panel in panels:
        label = _short_title(panel["title"])
        items.append(
            f'<div class="map-item" data-map-key="{panel["key"]}">'
            f'<button class="map-zoom" type="button" data-map-target="{panel["key"]}">'
            f'<span class="map-item-title">{label}</span>'
            '<span class="map-item-sub">Zoom to panel</span>'
            "</button>"
            f'<a class="map-doc" href="#/docs-about/{panel["doc"]}" '
            f'title="Open {panel["doc"]} documentation" aria-label="Open documentation">'
            '<svg class="icon" aria-hidden="true"><use href="#i-arrow"/></svg>'
            "</a>"
            "</div>"
        )
    index = (
        '<p class="map-hint">Click a panel to zoom. Every panel opens its '
        "documentation.</p>"
        f'<div class="map-list">{"".join(items)}</div>'
    )
    canvas = manifest["canvas"]
    return MapBundle(
        svg=CHEATSHEET_SVG.read_text(encoding="utf-8"),
        manifest=manifest,
        index_html=index,
        canvas_w=float(canvas["width"]),
        canvas_h=float(canvas["height"]),
    )


