def _section_files() -> list[Path]:
    """The snippet files, in the order the manifest declares."""
    return [SNIPPET_DIR / name for name in _SECTIONS]


def _substitute(text: str) -> str:
    def replace(match: re.Match[str]) -> str:
        name = match.group(1)
        if name not in _GENERATORS:
            msg = f"unknown generated block {name!r}"
            raise KeyError(msg)
        return _GENERATORS[name]()

    return _GENERATED_RE.sub(replace, text)


def build_readme() -> str:
    """Render the README from every snippet, in section order."""
    files = _section_files()
    missing = [path.name for path in files if not path.exists()]
    if missing:
        msg = f"manifest names snippets that do not exist: {missing}"
        raise FileNotFoundError(msg)
    preamble = files[0].read_text(encoding="utf-8").rstrip()
    sections = "\n\n".join(
        path.read_text(encoding="utf-8").rstrip() for path in files[1:]
    )
    return "\n\n".join((BANNER, preamble, _substitute(sections))) + "\n"


def main(argv: list[str] | None = None) -> int:
    """Write README.md, or report drift with ``--check``."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if README.md differs from the snippets (no write)",
    )
    args = parser.parse_args(argv)

    rendered = build_readme()
    if args.check:
        current = README.read_text(encoding="utf-8") if README.exists() else ""
        if current != rendered:
            print(
                "README.md is stale; run `uv run python docs/readme/build_readme.py`",
                file=sys.stderr,
            )
            return 1
        return 0

    README.write_text(rendered, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
