#!/usr/bin/env python
"""Generate the property-test modules that pin each spec's invariants.

The surface inventory reads one smoke path per spec row, so the path must be
derivable from the registry rather than hand-listed. Every registered spec gets
one module here; the reference entrypoint, the case builder, and the output
shape are all read from the spec.

    uv run python scripts/generate_property_tests.py [--check]

``--check`` writes nothing and exits non-zero when the tree is stale.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from computronium.acceleration.registry import all_specs
from computronium.acceleration.spec import ImplementationSpec

OUTPUT_DIR = Path("tests/property/generated")

_HEADER = '''"""Property tests for invariants of {spec_id}."""

# Generated by scripts/generate_property_tests.py
# Do not edit manually.

import hypothesis
import hypothesis.strategies as st
import pytest

from computronium.acceleration.registry import get

SPEC_ID = "{spec_id}"
CASE_MODULE = "{case_module}"
REFERENCE_MODULE = "{reference_module}"
REFERENCE_FUNCTION = "{reference_function}"


@pytest.fixture(scope="module")
def spec():
    return get(SPEC_ID)


def _run(seed: int):
    """One reference call on a case built from ``seed``."""
    from importlib import import_module

    cases = import_module(CASE_MODULE)
    reference = import_module(REFERENCE_MODULE)
    case = cases.make_case(seed=seed)
    call = getattr(reference, REFERENCE_FUNCTION)
{call}


@hypothesis.given(st.integers(min_value=0, max_value=1000))
@hypothesis.settings(max_examples=10, deadline=None)
def test_deterministic_under_fixed_seed(spec, seed):
    """Two calls under one seed produce the same output."""
    from computronium.acceleration.parity import digest

    assert digest(_run(seed)) == digest(_run(seed))
'''

_FINITE_TEST = '''

@hypothesis.given(st.integers(min_value=0, max_value=1000))
@hypothesis.settings(max_examples=10, deadline=None)
def test_state_remains_finite(spec, seed):
    """Every tensor in the output is finite (no NaN/Inf)."""
    import torch

    def _check(value, path="output"):
        if isinstance(value, torch.Tensor):
            assert not torch.isnan(value).any(), f"NaN found in {path}"
            assert not torch.isinf(value).any(), f"Inf found in {path}"
        elif isinstance(value, dict):
            for key, item in value.items():
                _check(item, f"{path}.{key}")
        elif isinstance(value, list | tuple):
            for index, item in enumerate(value):
                _check(item, f"{path}[{index}]")
        elif hasattr(value, "__dict__") and not isinstance(value, type):
            for key, item in vars(value).items():
                if not key.startswith("_"):
                    _check(item, f"{path}.{key}")

    _check(_run(seed))
'''

#: Reference entrypoints that take the case's own spec instead of the case.
_TAKES_SPEC = {"make_substrate"}


def _module_of(entrypoint: str) -> tuple[str, str]:
    module, _, function = entrypoint.rpartition(".")
    return module, function


def _call_body(reference_function: str) -> str:
    if reference_function in _TAKES_SPEC:
        return "    return call(case.spec)"
    return "    return call(case)"


def _slug(spec: ImplementationSpec) -> str:
    return spec.id.replace(".", "_")


def _render(spec: ImplementationSpec) -> str:
    reference_module, reference_function = _module_of(spec.reference_entrypoint)
    case_module = f"{reference_module.rpartition('.')[0]}.cases"
    body = _HEADER.format(
        spec_id=spec.id,
        case_module=case_module,
        reference_module=reference_module,
        reference_function=reference_function,
        call=_call_body(reference_function),
    )
    if reference_function not in _TAKES_SPEC:
        body += _FINITE_TEST
    return body


def _targets() -> dict[Path, str]:
    return {
        OUTPUT_DIR / f"test_{_slug(spec)}_invariants.py": _render(spec)
        for spec in all_specs()
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="report stale modules instead of writing them",
    )
    args = parser.parse_args()

    targets = _targets()
    stale = [
        path
        for path, content in targets.items()
        if not path.is_file() or path.read_text(encoding="utf-8") != content
    ]
    orphans = sorted(
        path for path in OUTPUT_DIR.glob("test_*_invariants.py") if path not in targets
    )

    if args.check:
        for path in (*stale, *orphans):
            print(path)
        return 1 if stale or orphans else 0

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    for path, content in targets.items():
        path.write_text(content, encoding="utf-8")
    for path in orphans:
        path.unlink()
    print(f"wrote {len(targets)} modules, removed {len(orphans)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
